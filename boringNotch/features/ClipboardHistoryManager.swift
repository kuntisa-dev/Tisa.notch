//
//  ClipboardHistoryManager.swift
//  boringNotch
//
//  Keeps an in-memory list of recently copied text and images.
//  Nothing is written to disk. Items marked as concealed or transient
//  (password managers, see nspasteboard.org) are never recorded.
//

import AppKit
import Combine
import Defaults

struct ClipboardEntry: Identifiable, Equatable {
    enum Content: Equatable {
        case text(String)
        case image(Data, NSPasteboard.PasteboardType)
    }

    let id: UUID
    let content: Content
    let date: Date
    let sourceBundleID: String?

    init(content: Content, date: Date = Date(), sourceBundleID: String?) {
        self.id = UUID()
        self.content = content
        self.date = date
        self.sourceBundleID = sourceBundleID
    }

    var previewText: String {
        switch content {
        case .text(let string):
            return string.trimmingCharacters(in: .whitespacesAndNewlines)
        case .image:
            return "Image"
        }
    }

    static func == (lhs: ClipboardEntry, rhs: ClipboardEntry) -> Bool {
        lhs.id == rhs.id
    }
}

@MainActor
final class ClipboardHistoryManager: ObservableObject {
    static let shared = ClipboardHistoryManager()

    @Published private(set) var entries: [ClipboardEntry] = []
    @Published private(set) var lastCopiedID: UUID?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var cancellables = Set<AnyCancellable>()

    /// Images larger than this are skipped to keep memory use small.
    private let maxImageBytes = 8 * 1024 * 1024

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    private init() {
        lastChangeCount = pasteboard.changeCount

        Defaults.publisher(.enableClipboardHistory)
            .sink { [weak self] change in
                Task { @MainActor in
                    if change.newValue {
                        self?.start()
                    } else {
                        self?.stop()
                        self?.clear()
                    }
                }
            }
            .store(in: &cancellables)

        Defaults.publisher(.clipboardHistoryLimit)
            .sink { [weak self] _ in
                Task { @MainActor in self?.trimToLimit() }
            }
            .store(in: &cancellables)
    }

    // MARK: - Monitoring

    func start() {
        guard timer == nil, Defaults[.enableClipboardHistory] else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        capture()
    }

    private func capture() {
        let types = pasteboard.types ?? []
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }

        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        // Prefer text: most copies (including from rich-text apps) carry a plain string.
        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(ClipboardEntry(content: .text(string), sourceBundleID: source))
            return
        }

        guard Defaults[.clipboardIncludeImages] else { return }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), data.count <= maxImageBytes {
                insert(ClipboardEntry(content: .image(data, type), sourceBundleID: source))
                return
            }
        }
    }

    private func insert(_ entry: ClipboardEntry) {
        // Move an identical item to the top instead of storing it twice.
        entries.removeAll { $0.content == entry.content }
        entries.insert(entry, at: 0)
        trimToLimit()
    }

    private func trimToLimit() {
        let limit = max(1, Defaults[.clipboardHistoryLimit])
        if entries.count > limit {
            entries.removeLast(entries.count - limit)
        }
    }

    // MARK: - Actions

    /// Puts an entry back on the clipboard so it can be pasted with ⌘V.
    func copy(_ entry: ClipboardEntry) {
        pasteboard.clearContents()
        switch entry.content {
        case .text(let string):
            pasteboard.setString(string, forType: .string)
        case .image(let data, let type):
            pasteboard.setData(data, forType: type)
        }
        // Don't record our own write as a new copy, just move the item up.
        lastChangeCount = pasteboard.changeCount
        if let index = entries.firstIndex(of: entry) {
            let moved = entries.remove(at: index)
            entries.insert(moved, at: 0)
        }
        lastCopiedID = entry.id
    }

    func remove(_ entry: ClipboardEntry) {
        entries.removeAll { $0.id == entry.id }
    }

    func clear() {
        entries.removeAll()
        lastCopiedID = nil
    }
}
